// Build a private, CPU-only, offline Kaggle script kernel that runs this batch's kaggle tasks.
//   node kaggle-pack.cjs <batch> <kernelDir> [workers]
// The script embeds the evaluator files and the task list; no tokens or repository contents beyond these.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const [batch, dir, workers = '4'] = process.argv.slice(2);
const files = ['lib.cjs', 'run.cjs', 'search.cjs', 'inputs.json', 'jsim.cjs', `jobs/${batch}.jsonl`];
const blob = Object.fromEntries(files.map(f => [f, fs.readFileSync(path.join(__dirname, f)).toString('base64')]));
const py = `# Generated by experiments/JSM/five-case/kaggle-pack.cjs for batch ${batch}
import base64, json, os, subprocess, time
FILES = json.loads(${JSON.stringify(JSON.stringify(blob))})
root = '/kaggle/working/five-case'
for name, data in FILES.items():
    p = os.path.join(root, name); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'wb').write(base64.b64decode(data).replace(b'\\r\\n', b'\\n'))
def sh(c): return subprocess.run(c, shell=True, capture_output=True, text=True).stdout.strip()
print('nproc', sh('nproc'), 'cpu.max', sh('cat /sys/fs/cgroup/cpu.max'), 'node', sh('node --version'), flush=True)
np = int(sh('nproc') or 1)
w = max(1, min(${Number(workers)}, np, 4))
t0 = time.time()
r = subprocess.run(['node', 'run.cjs', 'jobs/${batch}.jsonl', '--env', 'kaggle', '--workers', str(w), '--out', '/kaggle/working/out'], cwd=root)
print('exit', r.returncode, 'wall', round(time.time() - t0, 1), flush=True)
`;
fs.mkdirSync(dir, {recursive: true});
fs.writeFileSync(path.join(dir, 'run.py'), py);
fs.writeFileSync(path.join(dir, 'kernel-metadata.json'), JSON.stringify({
  id: 'jsmjsm/amr-jsm-five-case', title: 'amr-jsm-five-case', code_file: 'run.py', language: 'python', kernel_type: 'script',
  is_private: true, enable_gpu: false, enable_tpu: false, enable_internet: false, dataset_sources: [], competition_sources: [], kernel_sources: [],
}, null, 1));
console.log('packed', batch, Object.keys(blob).length, 'files', fs.statSync(path.join(dir, 'run.py')).size, 'bytes');
